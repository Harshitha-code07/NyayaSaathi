"""Draft document generation (text -> DOCX / PDF)."""
import io, datetime
from docx import Document
from fpdf import FPDF
KINDS = ["RTI application", "Consumer complaint / legal notice", "Security deposit demand notice"]
FOOT = "Draft generated by NyayaSaathi for information purposes. Review before use."

def build(kind, f):
    d = datetime.date.today().strftime("%d %B %Y"); n = f.get("name") or "[Your name]"; o = f.get("other") or "[Other party / Public Information Officer]"
    amt = f.get("amount") or "[amount]"; det = f.get("details") or "[describe the facts]"; when = f.get("when") or "[date]"; ad = f.get("address") or "[Your address]"
    if kind == KINDS[0]:
        return ("Application under the Right to Information Act, 2005", f"Date: {d}\n\nTo,\nThe Public Information Officer,\n{o}\n\nSubject: Request for information under the RTI Act, 2005\n\nSir/Madam,\n\nI, {n}, a citizen of India, request the following information:\n\n{det}\n\nI am enclosing the application fee as prescribed. If the information relates to another authority, please transfer this application as per the Act.\n\nYours faithfully,\n{n}\nAddress: {ad}")
    if kind == KINDS[1]:
        return ("Legal Notice / Consumer Complaint", f"Date: {d}\n\nTo,\n{o}\n\nSubject: Complaint regarding defective product / deficient service\n\nSir/Madam,\n\nI, {n}, state the following:\n\n{det}\n\nAmount paid: {amt}. Date of purchase/service: {when}.\n\nI request you to resolve this by refund, replacement or repair within 15 days of receiving this notice. Otherwise I will approach the appropriate Consumer Commission under the Consumer Protection Act, 2019, at your cost and risk.\n\nYours faithfully,\n{n}\nAddress: {ad}")
    return ("Demand Notice for Return of Security Deposit", f"Date: {d}\n\nTo,\n{o} (Landlord)\n\nSubject: Demand for refund of security deposit\n\nSir/Madam,\n\nI, {n}, was your tenant. I paid a security deposit of {amt}. I vacated the premises on {when}.\n\n{det}\n\nI request you to refund the deposit within 15 days of this notice. If not, I will pursue remedies available under the law, including the rent authority or civil court.\n\nYours faithfully,\n{n}\nAddress: {ad}")

def _s(t): return t.replace("\u20b9", "Rs.").encode("latin-1", "replace").decode("latin-1")

def to_docx(title, body):
    d = Document(); d.add_heading(title, 1)
    for p in body.split("\n"): d.add_paragraph(p)
    d.add_paragraph(FOOT).italic = True
    b = io.BytesIO(); d.save(b); return b.getvalue()

def to_pdf(title, body):
    p = FPDF(); p.add_page(); p.set_font("Helvetica", "B", 15); p.multi_cell(0, 9, _s(title), new_x="LMARGIN", new_y="NEXT"); p.ln(3)
    p.set_font("Helvetica", size=11)
    for line in body.split("\n"): p.multi_cell(0, 6, _s(line) or " ", new_x="LMARGIN", new_y="NEXT")
    p.ln(4); p.set_font("Helvetica", "I", 9); p.multi_cell(0, 5, FOOT, new_x="LMARGIN", new_y="NEXT")
    return bytes(p.output())
